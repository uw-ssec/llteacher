SHIM_LOG_DIR="${SKILL_SHIM_LOG_DIR:-/var/log/skill-shims}"
SHIM_FIXTURE_DIR="${SKILL_SHIM_FIXTURE_DIR:-/fixture}"
SHIM_REMOTE="${SKILL_SHIM_REMOTE:-/remote/origin.git}"
