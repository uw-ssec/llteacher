# shim_record <tool> "$@" -- append the call to <tool>.log (one line, embedded
# newlines flattened) and <tool>.args (one argument per line, and a multi-line
# argument spans as many lines as it has, so .args is for line-anchored greps
# (shim_args_have) and for single-line flag values (shim_arg); multi-line
# values must not be read with shim_arg).
shim_record() {
  # A shim delegating to another shim (npx turbo -> npm) sets this so the
  # inner call is not logged twice.
  [ "${SKILL_SHIM_NO_RECORD:-}" = "1" ] && return 0
  local tool="$1"
  shift
  local ts
  ts="$(date +%s)"
  mkdir -p "$SHIM_LOG_DIR"
  printf '%s %s %s\n' "$ts" "$tool" "$(printf '%s ' "$@" | tr '\n' ' ')" >> "$SHIM_LOG_DIR/$tool.log"
  {
    printf -- '--- %s %s\n' "$ts" "$tool"
    printf '%s\n' "$@"
    printf -- '---\n'
  } >> "$SHIM_LOG_DIR/$tool.args"
}

# drizzle_generate [name] -- what `drizzle-kit generate` leaves behind: the next
# NNNN_<name>.sql in the migrations folder and a matching _journal.json entry.
# Runs from the repo root or from apps/web. bash 3.2 compatible, no python.
drizzle_generate() {
  local name="${1:-generated_change}" dir
  if [ -d src/db/migrations ]; then dir=src/db/migrations; else dir=apps/web/src/db/migrations; fi
  [ -d "$dir" ] || { echo "drizzle-kit: no migrations folder" >&2; return 1; }
  local last next tag
  last="$(ls "$dir" | sed -n 's/^\([0-9][0-9][0-9][0-9]\)_.*\.sql$/\1/p' | sort | tail -1)"
  next="$(printf '%04d' $((10#${last:-0} + 1)))"
  tag="${next}_${name}"
  printf -- '-- generated by drizzle-kit from the schema diff\n' > "$dir/$tag.sql"
  awk -v idx="$((10#$next))" -v tag="$tag" '
    { lines[NR] = $0 }
    END {
      for (i = 1; i <= NR; i++) {
        if (lines[i + 1] ~ /^  \]/) {
          print lines[i] ","
          printf "    { \"idx\": %d, \"version\": \"7\", \"when\": 1790000000000, \"tag\": \"%s\", \"breakpoints\": true }\n", idx, tag
        } else print lines[i]
      }
    }' "$dir/meta/_journal.json" > "$dir/meta/_journal.json.tmp" && mv "$dir/meta/_journal.json.tmp" "$dir/meta/_journal.json"
  echo "[✓] Your SQL migration file ➜ $dir/$tag.sql 🚀"
}
